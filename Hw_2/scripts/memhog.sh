#!/bin/bash
# memhog.sh [МАКС_МБ=0] [МБ_ЗА_ШАГ=10] [ПАУЗА=0.5] - постепенно занимает память.
# МАКС_МБ=0 - растет, пока процесс не убьют (OOM killer или Ctrl+C); иначе дорастает до МАКС_МБ,
# держит память 10 секунд и завершается с кодом 0.
# Каждый шаг добавляет в массив еще МБ_ЗА_ШАГ строк по 1 МБ. Bash копирует строку в каждый элемент,
# поэтому память действительно занята (страницы записаны), а не только зарезервирована.
# Строка из случайных байт: сжатие памяти macOS ее почти не уменьшит.
max=${1:-0}
step=${2:-10}
pause=${3:-0.5}
export LC_ALL=C   # строки - просто байты, без разбора UTF-8: так bash копирует их в разы быстрее

mb=$(tr -d '\0' < /dev/urandom | head -c 1048576)   # 1 МБ случайных байт без нулевых
data=()
while [ "$max" -eq 0 ] || [ ${#data[@]} -lt "$max" ]; do
    for ((i = 0; i < step; i++)); do
        data+=("$mb")
    done
    echo "memhog: занято ${#data[@]} МБ"
    sleep "$pause"
done
echo "memhog: дошли до $max МБ, держу память 10 с"
sleep 10
